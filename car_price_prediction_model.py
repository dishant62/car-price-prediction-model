import gradio as gr
import pandas as pd

def predict_price(car_name, company, year, kms_driven, fuel_type):
    # Create a DataFrame from user input
    user_car_data = pd.DataFrame([[car_name, company, year, kms_driven, fuel_type]],
                                 columns=['name', 'company', 'year', 'kms_driven', 'fuel_type'])

    # Predict the price using the trained pipeline
    predicted_price = pipe.predict(user_car_data)[0]
    return f"Predicted car price: ₹{predicted_price:,.2f}"

# Get unique values for dropdowns from the 'df' DataFrame
car_names = df['name'].unique().tolist()
companies = df['company'].unique().tolist()
fuel_types = df['fuel_type'].unique().tolist()

# Create Gradio interface
iface = gr.Interface(
    fn=predict_price,
    inputs=[
        gr.Dropdown(choices=car_names, label="Car Name"),
        gr.Dropdown(choices=companies, label="Company"),
        gr.Number(label="Manufacturing Year (e.g., 2015)", precision=0),
        gr.Number(label="Kilometers Driven (e.g., 60000)", precision=0),
        gr.Dropdown(choices=fuel_types, label="Fuel Type")
    ],
    outputs="text",
    title="Car Price Predictor",
    description="Enter car details to get an estimated price."
)

# Launch the interface
iface.launch()